def f1(y,p):
    tp=tn=fp=fn=0
    for a,b in zip(y,p):
        if a==1 and b==1: tp+=1
        elif a==-1 and b==-1: tn+=1
        elif a==-1 and b==1: fp+=1
        else: fn+=1
    prec=tp/(tp+fp) if tp+fp else 0
    rec=tp/(tp+fn) if tp+fn else 0
    f1=2*prec*rec/(prec+rec) if prec+rec else 0
    acc=(tp+tn)/(tp+tn+fp+fn)
    return acc,f1

