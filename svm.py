def load_split(root,split):
    X=[]; y=[]
    for cls,lbl in [("NORMAL",-1),("PNEUMONIA",1)]:
        for fp in list_image_files(os.path.join(root,split,cls)):
            img=preprocess(load_image_grayscale_01(fp))
            X.append(img); y.append(lbl)
    return X,y

def run_pipeline(root):
    print("LOAD DATA")
    Xtr,ytr=load_split(root,"train")
    Xva,yva=load_split(root,"val")
    Xte,yte=load_split(root,"test")

    print("HOG EXTRACTION")
    Xtrf=to_features(Xtr+Xva)
    ypool=ytr+yva

    best=(0,0,0)
    for C in [0.5,1.0]:
        for g in [1e-3,1e-2]:
            print(f"TRAIN C={C} gamma={g}")
            svm=SVM(C,g).fit(Xtrf,ypool)
            acc,f1s=f1(ypool,svm.predict(Xtrf))
            print(" f1 =",f1s)
            if f1s>best[2]:
                best=(C,g,f1s)

    print("BEST:",best)

    print("FINAL TEST")
    svm=SVM(best[0],best[1]).fit(Xtrf,ypool)
    Xtef=to_features(Xte)
    print("TEST:",f1(yte,svm.predict(Xtef)))

