def list_image_files(folder):
    return sorted([
        os.path.join(folder, f)
        for f in os.listdir(folder)
        if f.lower().endswith((".jpg", ".png", ".jpeg"))
    ])

def load_image_grayscale_01(path):
    img = Image.open(path).convert("L")
    w, h = img.size
    data = list(img.getdata())
    out = [[0.0]*w for _ in range(h)]
    i = 0
    for y in range(h):
        for x in range(w):
            out[y][x] = data[i] / 255.0
            i += 1
    return out

def resize_bilinear(img, new_h, new_w):
    h, w = len(img), len(img[0])
    out = [[0.0]*new_w for _ in range(new_h)]
    ys = (h-1)/(new_h-1) if new_h > 1 else 0
    xs = (w-1)/(new_w-1) if new_w > 1 else 0

    for y2 in range(new_h):
        y = y2 * ys
        y0 = int(y); y1 = min(y0+1, h-1)
        wy = y - y0
        for x2 in range(new_w):
            x = x2 * xs
            x0 = int(x); x1 = min(x0+1, w-1)
            wx = x - x0
            v = (
                img[y0][x0]*(1-wx)*(1-wy) +
                img[y0][x1]*wx*(1-wy) +
                img[y1][x0]*(1-wx)*wy +
                img[y1][x1]*wx*wy
            )
            out[y2][x2] = v
    return out

def preprocess(img, size=(64,64)):
    img = resize_bilinear(img, size[0], size[1])
    flat = [v for r in img for v in r]
    m, s = mean(flat), stdev(flat)
    return [[(v-m)/s for v in r] for r in img]

