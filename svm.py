def hog_features(img, cell=8, bins=9):
    h, w = len(img), len(img[0])
    gx = [[0]*w for _ in range(h)]
    gy = [[0]*w for _ in range(h)]

    for y in range(h):
        for x in range(w):
            gx[y][x] = img[y][min(x+1,w-1)] - img[y][max(x-1,0)]
            gy[y][x] = img[min(y+1,h-1)][x] - img[max(y-1,0)][x]

    nc_y, nc_x = h//cell, w//cell
    hist = [[[0]*bins for _ in range(nc_x)] for _ in range(nc_y)]
    bw = 180/bins

    for cy in range(nc_y):
        for cx in range(nc_x):
            for y in range(cy*cell,(cy+1)*cell):
                for x in range(cx*cell,(cx+1)*cell):
                    mag = math.sqrt(gx[y][x]**2 + gy[y][x]**2)
                    ang = math.degrees(math.atan2(gy[y][x],gx[y][x]))%180
                    b = int(ang/bw)%bins
                    hist[cy][cx][b] += mag

    feat=[]
    for y in range(nc_y-1):
        for x in range(nc_x-1):
            block=[]
            for dy in range(2):
                for dx in range(2):
                    block.extend(hist[y+dy][x+dx])
            norm = math.sqrt(sum(v*v for v in block))+1e-6
            feat.extend([v/norm for v in block])
    return feat

def to_features(X):
    return [hog_features(img) for img in X]

# =========================================================
# SVM RBF (Simplified SMO)
# =========================================================

def rbf(x,z,g):
    return math.exp(-g*sum((a-b)**2 for a,b in zip(x,z)))

class SVM:
    def __init__(self,C=1.0,gamma=0.01,passes=2):
        self.C=C; self.gamma=gamma; self.passes=passes

    def fit(self,X,y):
        self.X=X; self.y=y
        m=len(X)
        self.a=[0.0]*m; self.b=0
        for _ in range(self.passes):
            for i in range(m):
                Ei=sum(self.a[k]*y[k]*rbf(X[k],X[i],self.gamma) for k in range(m))+self.b-y[i]
                if y[i]*Ei<-1e-3 and self.a[i]<self.C:
                    j=random.randrange(m)
                    Ej=sum(self.a[k]*y[k]*rbf(X[k],X[j],self.gamma) for k in range(m))+self.b-y[j]
                    ai,aj=self.a[i],self.a[j]
                    eta=2*rbf(X[i],X[j],self.gamma)-rbf(X[i],X[i],self.gamma)-rbf(X[j],X[j],self.gamma)
                    if eta>=0: continue
                    ajn=aj-y[j]*(Ei-Ej)/eta
                    ajn=clamp(ajn,0,self.C)
                    ain=ai+y[i]*y[j]*(aj-ajn)
                    self.a[i]=ain; self.a[j]=ajn
        return self

    def predict(self,X):
        out=[]
        for x in X:
            s=sum(self.a[k]*self.y[k]*rbf(self.X[k],x,self.gamma) for k in range(len(self.X)))+self.b
            out.append(1 if s>=0 else -1)
        return out

