root = os.path.join(path_extract,"Radiography")
run_pipeline(root)

def train_model(
    dataset_path: str,
    image_size=(64, 64),
    C_values=[0.5, 1.0],
    gamma_values=[1e-3, 1e-2],
    seed=42
):
    """
    dataset_path : path ke folder Radiography
    """

    set_seed(seed)

    # ===============================
    # Load Dataset
    # ===============================
    print("LOAD DATASET FROM:", dataset_path)

    Xtr, ytr = load_split(dataset_path, "train")
    Xva, yva = load_split(dataset_path, "val")
    Xte, yte = load_split(dataset_path, "test")

    print(f"Train: {len(Xtr)} | Val: {len(Xva)} | Test: {len(Xte)}")

    # ===============================
    # Feature Extraction (HOG)
    # ===============================
    print("EXTRACT HOG FEATURES")

    Xtrf = to_features(Xtr + Xva)
    ypool = ytr + yva

    # ===============================
    # Hyperparameter Search
    # ===============================
    best_C = None
    best_gamma = None
    best_f1 = 0

    for C in C_values:
        for gamma in gamma_values:
            print(f"TRAIN SVM | C={C} | gamma={gamma}")
            svm = SVM(C=C, gamma=gamma).fit(Xtrf, ypool)

            acc, f1_score = f1(ypool, svm.predict(Xtrf))
            print(f"  Acc={acc:.4f} | F1={f1_score:.4f}")

            if f1_score > best_f1:
                best_f1 = f1_score
                best_C = C
                best_gamma = gamma

    print("\nBEST PARAMETER")
    print("C =", best_C)
    print("gamma =", best_gamma)
    print("F1 =", best_f1)

    # ===============================
    # Final Evaluation on Test Set
    # ===============================
    print("\nFINAL TEST EVALUATION")

    svm = SVM(C=best_C, gamma=best_gamma).fit(Xtrf, ypool)
    Xtef = to_features(Xte)

    acc_test, f1_test = f1(yte, svm.predict(Xtef))
    print(f"TEST ACC = {acc_test:.4f}")
    print(f"TEST F1  = {f1_test:.4f}")

    return {
        "C": best_C,
        "gamma": best_gamma,
        "f1_val": best_f1,
        "acc_test": acc_test,
        "f1_test": f1_test
    }
