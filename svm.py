def set_seed(seed=42):
    random.seed(seed)

def clamp(x, lo, hi):
    return lo if x < lo else hi if x > hi else x

def mean(xs):
    return sum(xs) / (len(xs) if xs else 1)

def stdev(xs):
    if len(xs) < 2:
        return 1.0
    m = mean(xs)
    v = sum((x - m) ** 2 for x in xs) / (len(xs) - 1)
    return math.sqrt(v) if v > 1e-12 else 1.0

